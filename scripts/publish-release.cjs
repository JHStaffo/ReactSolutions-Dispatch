#!/usr/bin/env node
/*
 * Publishes the cPanel bundle to the `release` branch so a cPanel account can deploy with git:
 *   git clone --branch release <repo> ~/reactsolutions-dispatch   (once)
 *   ~/reactsolutions-dispatch/update.sh                            (every update)
 *
 * The branch holds only compiled code and runtime files (no source, no dev tools), and keeps a linear
 * history so `git pull --ff-only` always works on the server.
 *
 * Usage: npm run release            (build, commit to `release`, push to origin)
 *        npm run release -- --no-push
 * Run `npm run package` first, or use `npm run release`, which does it for you.
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.join(__dirname, '..');
const bundle = path.join(root, 'release', 'reactsolutions-dispatch');
const branch = process.env.RELEASE_BRANCH || 'release';
const remote = process.env.RELEASE_REMOTE || 'origin';
const push = !process.argv.includes('--no-push');
const git = (args, opts = {}) => String(execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...opts }) ?? '').trim();

if (!fs.existsSync(path.join(bundle, 'app.js'))) {
  console.error('No bundle found. Run `npm run package` first.');
  process.exit(1);
}

const sourceSha = git(['rev-parse', '--short', 'HEAD']);
const dirty = git(['status', '--porcelain', '--untracked-files=no']) !== '';
const wt = fs.mkdtempSync(path.join(os.tmpdir(), 'dispatch-release-'));
const inWt = (args) => git(args, { cwd: wt });

try {
  let exists = false;
  try {
    git(['fetch', '--quiet', remote, `+${branch}:refs/release-tmp/${branch}`], { stdio: process.env.RELEASE_DEBUG ? 'inherit' : 'ignore' });
    exists = true;
  } catch {
    /* no remote branch yet */
  }
  if (exists) {
    git(['worktree', 'add', '--quiet', '--detach', wt, `refs/release-tmp/${branch}`]);
  } else {
    git(['worktree', 'add', '--quiet', '--detach', wt]);
    inWt(['checkout', '--quiet', '--orphan', `tmp-release-${Date.now()}`]);
  }

  // Replace everything except .git with the fresh bundle.
  for (const e of fs.readdirSync(wt)) if (e !== '.git') fs.rmSync(path.join(wt, e), { recursive: true, force: true });
  fs.cpSync(bundle, wt, { recursive: true });
  fs.cpSync(path.join(root, 'deploy', 'update.sh'), path.join(wt, 'update.sh'));
  fs.chmodSync(path.join(wt, 'update.sh'), 0o755);
  fs.cpSync(path.join(root, 'deploy', 'release.gitignore'), path.join(wt, '.gitignore'));
  // Lock runtime dependency versions so every server install gets the same packages.
  execFileSync('npm', ['install', '--package-lock-only', '--omit=dev', '--no-audit', '--no-fund', '--loglevel=error'], { cwd: wt, stdio: 'inherit' });
  fs.writeFileSync(
    path.join(wt, 'RELEASE.txt'),
    `Built from ${sourceSha}${dirty ? ' (with uncommitted changes)' : ''} on ${new Date().toISOString()}\n` +
      'This branch is generated by `npm run release`. Do not edit it by hand.\n',
  );

  inWt(['add', '--all']);
  inWt(['update-index', '--chmod=+x', 'update.sh']);
  if (exists && inWt(['status', '--porcelain', '--', '.', ':!RELEASE.txt']) === '') {
    console.log(`Nothing changed; ${branch} already matches this build.`);
  } else {
    const env = { ...process.env };
    if (!env.GIT_AUTHOR_NAME && !safe(() => git(['config', 'user.name']))) {
      env.GIT_AUTHOR_NAME = env.GIT_COMMITTER_NAME = 'release-bot';
      env.GIT_AUTHOR_EMAIL = env.GIT_COMMITTER_EMAIL = 'release-bot@users.noreply.github.com';
    }
    execFileSync('git', ['commit', '--quiet', '-m', `Release from ${sourceSha}`], { cwd: wt, env, stdio: 'inherit' });
    const sha = inWt(['rev-parse', '--short', 'HEAD']);
    if (push) {
      inWt(['push', '--quiet', remote, `HEAD:refs/heads/${branch}`]);
      console.log(`Pushed ${branch} @ ${sha} (built from ${sourceSha}).`);
    } else {
      git(['branch', '--force', branch, sha]);
      console.log(`Committed ${branch} @ ${sha} locally (not pushed).`);
    }
  }
} finally {
  safe(() => git(['worktree', 'remove', '--force', wt]));
  safe(() => git(['update-ref', '-d', `refs/release-tmp/${branch}`]));
  fs.rmSync(wt, { recursive: true, force: true });
}

function safe(fn) {
  try {
    return fn();
  } catch {
    return '';
  }
}
